# ── Cell 4 — Audio loading and preprocessing helper
def load_and_preprocess_audio(file_path: str):
    """Load any supported audio file and return a 16 kHz mono tensor."""
    ext = os.path.splitext(file_path)[1].lower()

    if ext not in ('.wav', '.flac'):
        # pydub handles mp3 / m4a / ogg etc.
        audio_seg = AudioSegment.from_file(file_path)
        audio_seg = audio_seg.set_channels(1).set_frame_rate(SAMPLING_RATE)
        samples   = np.array(audio_seg.get_array_of_samples(), dtype=np.float32)
        samples  /= 2**15                           # normalise to [-1, 1]
        waveform_16k = torch.from_numpy(samples)
        orig_sr      = SAMPLING_RATE                # already resampled by pydub
    else:
        waveform, orig_sr = torchaudio.load(file_path)
        if waveform.shape[0] > 1:                   # stereo → mono
            waveform = waveform.mean(dim=0, keepdim=True)
        if orig_sr != SAMPLING_RATE:
            waveform = torchaudio.transforms.Resample(orig_sr, SAMPLING_RATE)(waveform)
        waveform_16k = waveform.squeeze()

    duration_s = len(waveform_16k) / SAMPLING_RATE
    return waveform_16k, orig_sr, duration_s

print("✅ Preprocessing helper defined.")

# ── Cell 5 — VAD speech-boundary detection
def detect_speech_segments(waveform_16k: torch.Tensor):
    """Run Silero VAD and return raw speech timestamp dicts."""
    timestamps = get_speech_timestamps(
        waveform_16k,
        vad_model,
        sampling_rate=SAMPLING_RATE,
        threshold=VAD_THRESHOLD,
        min_silence_duration_ms=300,
        min_speech_duration_ms=int(MIN_SEGMENT_DURATION_S * 1000),
        return_seconds=False,
    )
    print(f"   VAD found {len(timestamps)} raw speech region(s).")
    return timestamps

print("✅ VAD detection function defined.")

# ── Cell 6 — Energy-based split point search ──────────────────────────────────
def find_energy_split_point(
    waveform_16k: torch.Tensor,
    ideal_end_sample: int,
) -> int:
    """
    Scan backwards from `ideal_end_sample` through SEARCH_WINDOW_S of audio
    and return the sample index of the quietest QUIET_CHUNK_MS window.

    This is almost always a word or sentence boundary.

    If the entire search window is above the noise floor (extremely dense
    speech with no pauses), returns None so the caller can fall back to the
    hard cut and log a warning.

    Parameters
    ----------
    waveform_16k      : full audio tensor (1-D, float32, 16 kHz)
    ideal_end_sample  : where the hard cut *would* have been (= 30 s mark)

    Returns
    -------
    int | None  — best cut sample, or None if no quiet region found
    """
    chunk_samples  = int(QUIET_CHUNK_MS / 1000 * SAMPLING_RATE)   # e.g. 1600
    window_samples = int(SEARCH_WINDOW_S * SAMPLING_RATE)         # e.g. 80 000

    # Search range: [search_start … ideal_end_sample]
    search_start = max(0, ideal_end_sample - window_samples)
    audio_region = waveform_16k[search_start:ideal_end_sample].numpy()

    if len(audio_region) < chunk_samples:
        return None   # not enough audio to probe

    # Slide a QUIET_CHUNK_MS window and record RMS energy at each position
    best_rms       = float('inf')
    best_cut       = None
    step           = chunk_samples // 2        # 50 % overlap for smoother search

    for offset in range(0, len(audio_region) - chunk_samples + 1, step):
        chunk = audio_region[offset : offset + chunk_samples]
        rms   = float(np.sqrt(np.mean(chunk ** 2)))
        if rms < best_rms:
            best_rms = rms
            # Cut at the *start* of the quietest window (natural pause onset)
            best_cut = search_start + offset

    return best_cut   # may still be None if the loop never ran

print("✅ Energy-based split point search defined.")

# ── Cell 7 — Merge + energy-search split to respect the 30 s ceiling ──────────
def merge_into_max_segments(
    timestamps,
    total_samples: int,
    waveform_16k: torch.Tensor,
):
    """
    Merge consecutive VAD chunks into segments ≤ MAX_SEGMENT_DURATION_S.

    Two-pass approach:
      Pass 1 — greedily merge at VAD-detected silence boundaries.
      Pass 2 — any segment still > max (dense speech with no internal silence)
               is split using find_energy_split_point() instead of a blind
               sample-count cut.
               Falls back to hard cut ONLY when no quiet region is found, and
               logs a warning with the exact timestamp.

    Parameters
    ----------
    timestamps    : list of {'start': int, 'end': int} from Silero VAD
    total_samples : total length of waveform_16k in samples
    waveform_16k  : full audio tensor (needed for energy search in Pass 2)
    """
    max_samples = MAX_SEGMENT_DURATION_S * SAMPLING_RATE
    segments    = []

    if not timestamps:
        print("   ⚠️  No speech detected. Returning full audio as one segment.")
        return [(0, total_samples)]

    # ── Pass 1: merge at VAD silence boundaries ───────────────────────────────
    seg_start = timestamps[0]['start']
    seg_end   = timestamps[0]['end']

    for ts in timestamps[1:]:
        if (ts['end'] - seg_start) <= max_samples:
            seg_end = ts['end']                         # still fits — extend
        else:
            segments.append((seg_start, seg_end))       # close current segment
            seg_start = ts['start']
            seg_end   = ts['end']

    segments.append((seg_start, seg_end))               # flush the tail

    # ── Pass 2: energy-based split for anything still over the limit ──────────
    final_segments  = []
    hard_cut_count  = 0

    for (start, end) in segments:
        while (end - start) > max_samples:
            ideal_cut = start + int(max_samples)        # where the hard cut would be

            cut = find_energy_split_point(waveform_16k, ideal_cut)

            if cut is not None and cut > start:
                # ✅ Found a natural quiet boundary — use it
                final_segments.append((start, cut))
                start = cut
            else:
                # ⚠️ No quiet region found — fall back to hard cut and warn
                hard_cut_count += 1
                cut_time_s = ideal_cut / SAMPLING_RATE
                print(
                    f"   ⚠️  WARNING: no quiet region found near "
                    f"{cut_time_s:.2f} s — hard cut applied at that point. "
                    f"Consider reducing SEARCH_WINDOW_S or checking the audio "
                    f"for unusually dense speech."
                )
                final_segments.append((start, ideal_cut))
                start = ideal_cut

        if end > start:                                 # keep non-empty remainder
            final_segments.append((start, end))

    summary = (
        f"   Merged into {len(final_segments)} output segment(s) "
        f"(Pass-1 VAD boundaries: {len(segments)}"
    )
    if hard_cut_count:
        summary += f", energy splits used, {hard_cut_count} hard-cut fallback(s)"
    else:
        summary += ", all oversized chunks split at natural boundaries"
    summary += ")."
    print(summary)

    return final_segments

print("✅ Segment merging function defined.")

# ── Cell 8 — Save segments to disk as 16 kHz mono WAV files ──────────────────
def save_segments(waveform_16k: torch.Tensor, segments, base_name: str):
    """Slice the waveform at computed boundaries and write WAV files."""
    saved_paths   = []
    total_samples = len(waveform_16k)

    for i, (start, end) in enumerate(segments):
        start    = max(0, int(start))
        end      = min(int(end), total_samples)
        chunk    = waveform_16k[start:end].numpy()
        duration = (end - start) / SAMPLING_RATE
        out_path = os.path.join(OUTPUT_DIR, f"{base_name}_segment_{i+1:03d}.wav")
        sf.write(out_path, chunk, SAMPLING_RATE, subtype='PCM_16')
        saved_paths.append(out_path)
        print(f"   Saved segment {i+1:3d} | {duration:6.2f} s → {out_path}")

    return saved_paths

print("✅ Segment saving function defined.")

# ── Cell 9 — Master pipeline function ─────────────────────────────────────────
def split_audio(file_path: str):
    """
    Full pipeline: load → preprocess → VAD → merge+energy-split → save.
    Returns a list of saved segment file paths.
    """
    print(f"\n{'='*55}\n Processing: {os.path.basename(file_path)}\n{'='*55}")

    print("[1/4] Loading and preprocessing...")
    waveform_16k, orig_sr, duration_s = load_and_preprocess_audio(file_path)
    print(f"       Duration   : {duration_s:.2f} s")
    print(f"       Original SR: {orig_sr} Hz")

    # Short-circuit: already within the limit
    if duration_s <= MAX_SEGMENT_DURATION_S:
        print(f"   ℹ️  Already within {MAX_SEGMENT_DURATION_S} s — saving as-is.")
        base = os.path.splitext(os.path.basename(file_path))[0]
        out  = os.path.join(OUTPUT_DIR, f"{base}_segment_001.wav")
        sf.write(out, waveform_16k.numpy(), SAMPLING_RATE, subtype='PCM_16')
        return [out]

    print("[2/4] Running VAD...")
    timestamps = detect_speech_segments(waveform_16k)

    print("[3/4] Merging into output segments (energy-based split)...")
    segments = merge_into_max_segments(timestamps, len(waveform_16k), waveform_16k)

    print("[4/4] Saving segments...")
    base_name = os.path.splitext(os.path.basename(file_path))[0]
    saved = save_segments(waveform_16k, segments, base_name)

    print(f"\n✅ Done — {len(saved)} segment(s) written to '{OUTPUT_DIR}/'")
    return saved

print("✅ split_audio() pipeline ready.")

