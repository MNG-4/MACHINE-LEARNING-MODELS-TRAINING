# ── Show original audio as soon as a file is selected ─────────────────────────
def on_upload_change(change):
    with original_out:
        clear_output(wait=True)
        if not uploader.value:
            return

        uploaded  = list(uploader.value.values())[0]
        fname     = list(uploader.value.keys())[0]
        ext       = os.path.splitext(fname)[1].lower()
        raw_bytes = bytes(uploaded['content'])

        # Write to a temp file so soundfile can decode any format
        tmp = tempfile.NamedTemporaryFile(suffix=ext, delete=False)
        tmp.write(raw_bytes)
        tmp.flush()
        tmp_path = tmp.name
        tmp.close()

        try:
            data, sr = sf.read(tmp_path)
            dur = len(data) / sr
            display(HTML(
                f"<b>📂 Original:</b> {fname} &nbsp;|&nbsp; "
                f"{dur:.2f} s &nbsp;|&nbsp; {sr} Hz"
            ))
            display(Audio(data=data, rate=sr, autoplay=False))
        except Exception as e:
            print(f"⚠️  Could not preview original file: {e}")
        finally:
            os.unlink(tmp_path)

uploader.observe(on_upload_change, names='value')

