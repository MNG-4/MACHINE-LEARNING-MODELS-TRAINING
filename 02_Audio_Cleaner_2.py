def load_audio(path, sr=SAMPLE_RATE):
    y, _ = librosa.load(str(path), sr=sr, mono=True)
    return y

def augment_audio(y, sr=SAMPLE_RATE):
    """
    Applies random augmentations directly to the raw audio
    to force the model to learn structural invariance.
    """
    # 1. Random Pitch Shifting (-2 to +2 semitones)
    if np.random.rand() > 0.5:
        n_steps = np.random.uniform(-2.0, 2.0)
        y = librosa.effects.pitch_shift(y, sr=sr, n_steps=n_steps)

    # 2. Random Time Stretching (0.8x slower to 1.2x faster)
    if np.random.rand() > 0.5:
        rate = np.random.uniform(0.8, 1.2)
        y = librosa.effects.time_stretch(y, rate=rate)

    return y

def extract_mfcc_features(segment_audio, sr=SAMPLE_RATE):
    """
    Returns a (T, 120) sequence feature matrix (MFCCs + Delta + Delta-Delta)
    Without compressing the time dimension.
    """
    frame_len = int(sr * FRAME_DURATION)
    hop_len   = int(sr * HOP_DURATION)

    if len(segment_audio) < frame_len:
        segment_audio = np.pad(segment_audio, (0, frame_len - len(segment_audio)))

    mfcc   = librosa.feature.mfcc(y=segment_audio, sr=sr, n_mfcc=N_MFCC,
                                   n_fft=frame_len, hop_length=hop_len)
    delta  = librosa.feature.delta(mfcc)
    delta2 = librosa.feature.delta(mfcc, order=2)

    features = np.concatenate([mfcc, delta, delta2], axis=0).T  # Returns shape (T, 120)
    return features.astype(np.float32)

