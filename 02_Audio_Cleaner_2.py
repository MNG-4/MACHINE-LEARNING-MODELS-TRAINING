def parse_label_file(label_path):
    segments = []
    with open(label_path, "r") as f:
        for lineno, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            parts = line.split("\t")
            if len(parts) != 3:
                print(f"Warning: Line {lineno} in {label_path.name} does not have 3 tab-separated parts: {line}")
                continue
            try:
                start = float(parts[0])
                end   = float(parts[1])
                raw   = parts[2].strip().lower()
                canonical = LABEL_MAP.get(raw)
                if canonical is None:
                    print(f"Warning: Unknown label '{raw}' in line {lineno} of {label_path.name}")
                    continue
                segments.append((start, end, CLASS_TO_IDX[canonical]))
            except ValueError:
                print(f"Warning: Could not parse start/end times in line {lineno} of {label_path.name}: {line}")
                continue
    return segments

