def build_temporal_model(n_features, n_classes):
    # Notice: Shape accepts explicit temporal dimension sequence arrays now!
    inputs = layers.Input(shape=(MAX_TIMESTEPS, n_features), name="sequential_input")

    # Tracking frame transitions dynamically over the timeline
    x = layers.Bidirectional(
            layers.LSTM(128, return_sequences=True, dropout=0.3,
                        recurrent_dropout=0.2), name="bilstm_sequence_1")(inputs)
    x = layers.Bidirectional(
            layers.LSTM(64, return_sequences=False, dropout=0.3,
                        recurrent_dropout=0.2), name="bilstm_sequence_2")(x)

    x = layers.Dense(64, activation="relu")(x)
    x = layers.Dropout(0.4)(x)
    outputs = layers.Dense(n_classes, activation="softmax", name="class_probs")(x)

    model = models.Model(inputs, outputs)
    model.compile(
        optimizer=optimizers.Adam(LEARNING_RATE),
        loss="sparse_categorical_crossentropy",
        metrics=["accuracy"]
    )
    return model

